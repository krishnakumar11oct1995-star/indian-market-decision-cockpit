"""
Telegram Instant Alert Dispatcher Engine
Sends formatted mobile trade alerts and IPO notifications via Telegram Bot API.
"""

import requests
from typing import Dict, Any, Tuple

def send_telegram_notification(
    bot_token: str,
    chat_id: str,
    message_html: str
) -> Tuple[bool, str]:
    """
    Sends an HTML-formatted message to a user or channel via Telegram Bot API.
    Returns: (Success: bool, Message: str)
    """
    if not bot_token or not chat_id:
        return False, "Bot Token and Chat ID are required."
        
    url = f"https://api.telegram.org/bot{bot_token.strip()}/sendMessage"
    payload = {
        "chat_id": chat_id.strip(),
        "text": message_html,
        "parse_mode": "HTML",
        "disable_web_page_preview": True
    }
    
    try:
        resp = requests.post(url, json=payload, timeout=8)
        if resp.status_code == 200:
            return True, "Alert successfully sent to Telegram!"
        else:
            err = resp.json().get("description", f"HTTP {resp.status_code}")
            return False, f"Telegram API Error: {err}"
    except Exception as e:
        return False, f"Connection Failed: {e}"

def format_trade_alert(card: Dict[str, Any]) -> str:
    """
    Formats a stock trade setup into a structured, emoji-rich Telegram message.
    """
    ticker = card.get("Ticker", "UNKNOWN")
    cmp = card.get("CMP", 0.0)
    verdict = card.get("Trade_Verdict", card.get("Signal", "Buy"))
    conviction = card.get("Conviction_Score", 60)
    sl = card.get("Stop_Loss", 0.0)
    sl_pct = card.get("SL_Pct", 2.0)
    t_base = card.get("Target_Base", 0.0)
    t_pct = card.get("Target_Base_Pct", 5.0)
    rr = card.get("Risk_Reward", 2.0)
    entry = card.get("Entry_Zone", f"₹{cmp:.1f}")
    catalyst = card.get("News_Catalyst", card.get("Thesis", "Technical momentum"))

    msg = f"""<b>🎯 NEW TRADE BLUEPRINT: {ticker}</b>
━━━━━━━━━━━━━━━━━━━━
<b>Verdict:</b> {verdict} (Conviction: {conviction}/100)
<b>Current Market Price:</b> ₹{cmp:,.2f}
<b>Suggested Entry:</b> {entry}

🛑 <b>Stop-Loss:</b> ₹{sl:,.2f} (-{sl_pct}%)
🎯 <b>Target 1:</b> ₹{t_base:,.2f} (+{t_pct}%)
⚖️ <b>Risk:Reward:</b> 1 : {rr:.2f}x

📰 <b>Catalyst:</b>
<i>{catalyst}</i>

💡 <i>Generated by Indian Market Decision Cockpit</i>"""
    return msg

def format_ipo_alert(ipo: Dict[str, Any]) -> str:
    """
    Formats an IPO update into a structured Telegram message.
    """
    comp = ipo.get("Company_Name", "IPO")
    cat = ipo.get("Category", "Mainboard")
    status = ipo.get("Status", "Open")
    price = ipo.get("Price_Band", "-")
    gmp = ipo.get("GMP_Val", 0.0)
    gain = ipo.get("Est_Gain_Pct", 0.0)
    dates = ipo.get("Dates", "TBA")
    verdict = ipo.get("Verdict", "APPLY FOR LISTING GAINS")

    msg = f"""<b>🚀 IPO RADAR ALERT: {comp}</b>
━━━━━━━━━━━━━━━━━━━━
<b>Category:</b> {cat} | <b>Status:</b> {status}
<b>Price Band:</b> ₹{price}
<b>Dates:</b> {dates}

🔥 <b>Latest GMP:</b> ₹{gmp:.1f} (<b>{gain:+.1f}%</b> Est. Pop)
🎯 <b>AI Verdict:</b> {verdict}

💡 <i>Generated by Indian Market Decision Cockpit</i>"""
    return msg
